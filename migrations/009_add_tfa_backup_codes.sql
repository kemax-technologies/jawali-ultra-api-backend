-- Migration 009: رموز الاسترداد الاحتياطية (Backup Codes) للمصادقة الثنائية
-- ─────────────────────────────────────────────────────────────────────────────
-- السياق: مراجعة أمنية/UX عميقة لشاشتي "إعداد 2FA" و"التحقق من 2FA" كشفت
-- أن فقدان جهاز المصادقة (هاتف مفقود/تطبيق مُزال) كان يعني عدم وجود أي مسار
-- استرداد ذاتي لحساب مدير مفعَّل عليه 2FA — الحل الوحيد المتاح كان تواصلاً
-- يدوياً مع الدعم لتعطيل 2FA من قاعدة البيانات مباشرة، وهي ممارسة غير عملية
-- وغير مطابقة لمعيار الصناعة الشائع في كل تطبيقات 2FA الجادة.
--
-- الحل: يحصل المستخدم على 10 رموز استرداد لمرة واحدة فقط عند أول تفعيل لـ2FA
-- (action=setup_2fa_confirm) أو عند إعادة توليدها صريحاً من الإعدادات
-- (action=regenerate_backup_codes) — تُعرض نصاً واضحاً في تلك اللحظة فقط،
-- ثم لا تُعرض مطلقاً مرة أخرى (فقط عدّاد "المتبقي" غير المُستهلَك). يمكن
-- استخدام أي رمز واحد بدل رمز TOTP الستّ خانات عند تسجيل الدخول
-- (action=verify_2fa) — يُستهلَك فوراً عند الاستخدام (لا يصلح للاستخدام
-- مرتين).
--
-- ملاحظة أمنية: تُخزَّن الرموز هنا بصيغة bcrypt (password_hash) لا نصاً
-- واضحاً — خلافاً لعمود users.tfa_secret (الذي يتطلب عكسية الخوارزمية
-- لحساب TOTP)، رموز الاسترداد لا تحتاج أي عملية عكسية على الخادم؛ يكفي
-- التحقق أحادي الجهة (one-way) تماماً كحال password_hash لكلمات المرور.
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS tfa_backup_codes (
    id          SERIAL PRIMARY KEY,
    user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    code_hash   VARCHAR(255) NOT NULL,
    used_at     TIMESTAMP DEFAULT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_tfa_backup_codes_user ON tfa_backup_codes (user_id);
CREATE INDEX IF NOT EXISTS idx_tfa_backup_codes_unused ON tfa_backup_codes (user_id, used_at);

-- ملاحظة: لا حاجة لأي بيانات ابتدائية — الحسابات التي فعّلت 2FA سابقاً (قبل
-- هذا الترحيل) لن تحصل على رموز استرداد تلقائياً؛ يُطلب منها فقط الضغط على
-- "إعادة توليد الرموز الاحتياطية" مرة واحدة من شاشة الإعدادات للحصول عليها
-- (يتطلب تأكيد كلمة المرور، تماماً كأي إعادة توليد لاحقة).
