-- ─────────────────────────────────────────────────────────────────────────────
-- Migration 004: إضافة تحقق 2FA (TOTP) على مستوى الخادم
-- ─────────────────────────────────────────────────────────────────────────────
-- السياق: كانت المصادقة الثنائية (2FA) منفَّذة 100% على جهاز العميل (Flutter)
-- فقط — التطبيق كان يحسب/يتحقق من رمز TOTP محلياً بدون أي معرفة من الخادم
-- بأن 2FA "مفعَّل" لهذا الحساب. هذا يعني أن auth.php?action=login كان يُصدر
-- JWT كامل الصلاحيات فوراً بعد نجاح كلمة المرور فقط، بصرف النظر تماماً عن
-- حالة 2FA — فأي عميل يتجاوز واجهة Flutter (مثل طلب curl/Postman مباشر)
-- يحصل على وصول كامل دون أي تحدي 2FA، مما يُفرغ الميزة من قيمتها الأمنية
-- الحقيقية لحسابات المدراء.
--
-- الحل: تخزين سر TOTP (Base32) وحالة التفعيل في قاعدة البيانات نفسها،
-- ليصبح الخادم (auth.php) هو الحَكَم الوحيد في تحديد ما إذا كان تسجيل الدخول
-- يتطلب رمز 2FA قبل إصدار أي JWT صالح للاستخدام في باقي الـ API.
--
-- ملاحظة أمنية: تخزين سر TOTP بنص واضح (غير مُجزَّأ/hash) في هذا العمود هو
-- أمر متوقَّع ومعتاد في تطبيقات TOTP (على عكس كلمات المرور) — لأن خوارزمية
-- HMAC-SHA1 المستخدمة للتحقق من الرمز تتطلب السر الأصلي القابل للعكس، لا
-- يمكن التحقق من رمز TOTP من قيمة مُجزَّأة بشكل one-way. الحماية تأتي من:
--  (1) الوصول لقاعدة البيانات محصور بمفاتيح اتصال الخادم فقط (لا يُعرض هذا
--      العمود مطلقاً في أي استجابة API للعميل)،
--  (2) اتصال TLS/SSL إلزامي لقاعدة بيانات Supabase.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE users ADD COLUMN IF NOT EXISTS tfa_enabled SMALLINT NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS tfa_secret  VARCHAR(64) DEFAULT NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS tfa_enabled_at TIMESTAMP DEFAULT NULL;

CREATE INDEX IF NOT EXISTS idx_users_tfa_enabled ON users (tfa_enabled);

-- ملاحظة: لا حاجة لأي بيانات ابتدائية — كل الحسابات الحالية تبدأ
-- بـ tfa_enabled = 0 (غير مفعَّل) بشكل طبيعي، وسيُطلب من المدراء الذين
-- فعّلوا 2FA محلياً فقط (قبل هذا الترحيل) إعادة الإعداد مرة واحدة عبر
-- شاشة "إعداد المصادقة الثنائية" ليُسجَّل السر على الخادم أيضاً.
