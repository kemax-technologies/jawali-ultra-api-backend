-- ─────────────────────────────────────────────────────────────────────────────
-- Task 11 — جدول تتبّع ملفات الترحيل (schema_migrations)
-- ─────────────────────────────────────────────────────────────────────────────
-- السياق: كانت ملفات الترحيل (000 إلى 007) تُطبَّق يدوياً على قاعدة بيانات
-- الإنتاج (عبر SQL Editor في Supabase أو psql مباشرة) بدون أي جدول أو آلية
-- تُسجِّل أي ملفات طُبِّقت فعلاً، وفي أي وقت، وعلى أي قاعدة بيانات (تطوير/
-- إنتاج) — الاعتماد الوحيد كان "الذاكرة والتوثيق النصي في تعليقات الملفات".
-- هذا خطر حقيقي: لا توجد طريقة آلية لمعرفة "هل هذا الترحيل طُبِّق هنا أم لا؟"
-- عند الانتقال لخادم/قاعدة بيانات جديدة، أو عند الشك بعد انقطاع أثناء التطبيق.
--
-- هذا الملف يُنشئ جدول التتبّع الذي يستخدمه أداة التشغيل migrate.php (بجانب
-- المجلد) لمعرفة: أي الملفات طُبِّقت، بأي checksum (لرصد أي تعديل لاحق على
-- ملف مُطبَّق مسبقاً — وهو ممنوع كما هو موضّح في migrations/README.md)،
-- ومتى، وكيف (يدوياً/عبر الأداة).
--
-- ملاحظة تصميمية مقصودة: migrate.php ينفّذ "CREATE TABLE IF NOT EXISTS" لهذا
-- الجدول نفسه بشكل احترازي عند بدء تشغيله (لحل مشكلة "الدجاجة والبيضة" —
-- لا يمكن معرفة ما هو "معلَّق" دون هذا الجدول أصلاً) — لذا تنفيذ هذا الملف
-- عبر الأداة نفسها هو عملية "no-op" آمنة تماماً (IF NOT EXISTS)، والقيمة
-- الحقيقية منه هي توثيق وجود هذا الجدول رسمياً كجزء من تاريخ الترحيلات
-- بدل أن يكون "سحرياً" غير مُوثَّق في أي مكان.
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS schema_migrations (
    id            SERIAL PRIMARY KEY,
    filename      VARCHAR(255) NOT NULL UNIQUE,
    checksum      VARCHAR(64)  NOT NULL,          -- sha256(محتوى الملف) وقت التطبيق
    applied_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    applied_by    VARCHAR(20)  NOT NULL DEFAULT 'manual', -- 'manual' | 'migrate_cli'
    execution_ms  INTEGER                          -- زمن التنفيذ (NULL لسجلات backfill اليدوية)
);

COMMENT ON TABLE schema_migrations IS
    'تتبّع ملفات الترحيل المُطبَّقة على هذه القاعدة — راجع migrations/README.md';
