-- السياق (فحص معماري شامل — طلب المستخدم الصريح بربط حقيقي بين المحاسبة
-- والعملاء/الذمم، لا مجرد روابط تنقّل سطحية): قبل هذا الترحيل، كانت دفعة
-- سداد الذمم (credit_payments) تُحدِّث فقط الرصيد الرقمي على القيد
-- (credits.paid_yer/paid_usd) بلا أي ربط حقيقي بأي صندوق/بنك فعلي استُلمت
-- فيه الدفعة — أي أن المال يُسجَّل "متحصَّلاً" محاسبياً بلا أي أثر نقدي
-- حقيقي قابل للتتبع في أي صندوق. هذا يمنع الترحيل المحاسبي التلقائي
-- الصحيح (مدين: الصندوق ← دائن: الذمم المدينة) من الاعتماد على بيانات
-- مُخزَّنة فعلياً على الخادم (كان يعتمد فقط على التحديث المحلي المؤقت في
-- تطبيق Flutter دون أي تثبيت خادمي).
--
-- هذا العمود اختياري تماماً (NULL يعني: دفعة مُسجَّلة بلا ربط بصندوق محدد
-- بعد — سلوك متوافق 100% مع كل الدفعات القديمة قبل هذا الترحيل، ولن يُكسر
-- أي بيانات موجودة). لا FK صارم إلى cash_accounts(id) عمداً — بنفس تماماً
-- نمط payroll_runs.cash_account_id الموجود مسبقاً في هذا المشروع (يتجنّب
-- تعقيد قواعد الحذف المتتالي عبر tenants متعددين على نفس الجدول المشترك).
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE credit_payments
    ADD COLUMN IF NOT EXISTS cash_account_id VARCHAR(40);

COMMENT ON COLUMN credit_payments.cash_account_id IS
    'الصندوق/البنك الذي استُلمت فيه الدفعة فعلياً (اختياري) — أساس الترحيل المحاسبي التلقائي الصحيح (مدين: الصندوق ← دائن: الذمم المدينة). NULL = دفعة غير مربوطة بصندوق محدد.';

-- فهرس يُسرّع أي استعلام مستقبلي يربط دفعات الذمم بصندوق معيّن (مثل كشف
-- حساب الصندوق أو تقرير تسوية الصندوق مقابل قيود اليومية المرحَّلة).
CREATE INDEX IF NOT EXISTS idx_credit_payments_cash_account ON credit_payments(cash_account_id);
