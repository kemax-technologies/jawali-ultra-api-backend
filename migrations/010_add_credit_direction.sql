-- Migration 010: إضافة عمود اتجاه القيد (direction) إلى دفتر ديون العملاء
-- ─────────────────────────────────────────────────────────────────────────────
-- السياق: تطوير "دفتر ديون العملاء" (Task F) أضاف دعم قيدين من نوعين:
--   'debit'  = "عليه" (العميل مدين للمتجر — ذمة مستحقة لنا؛ السلوك الافتراضي
--              التاريخي لكل مبيعات نقطة البيع الآجلة، ولا يزال الافتراضي).
--   'credit' = "له"   (المتجر مدين للعميل — رصيد لصالحه، مثل دفعة زائدة أو
--              مبلغ يُخصم من مشترياته القادمة). هذا النوع جديد بالكامل ولم
--              يكن مدعوماً من قبل في أي مكان بالنظام.
--
-- ⚠️ خطأ فادح تم رصده واكتشافه قبل هذا الترحيل: كود Flutter (CreditEntry
-- .toMap/.fromMap) وواجهة "دَين جديد" كانا يرسلان/يتوقعان حقل `direction`،
-- لكن جدول `credits` في قاعدة الإنتاج (Supabase/PostgreSQL) لا يحتوي على هذا
-- العمود إطلاقاً، و credits.php (POST/GET) لا يحفظه أو يرجعه في الاستجابة.
-- النتيجة: أي قيد "له" يُنشأ من التطبيق كان يُحفَظ في الذاكرة المحلية بشكل
-- صحيح مؤقتاً، لكن بعد المزامنة مع الخادم (أو إعادة تحميل التطبيق من
-- الخادم) كان `direction` يُفقد ويرجع دائماً 'debit' الافتراضي — أي أن كل
-- قيود "له" كانت ستتحوّل ضمناً إلى "عليه" فعليّاً في قاعدة البيانات
-- والتقارير المالية بعد أول مزامنة. هذا الترحيل + تحديث credits.php المرتبط
-- به يُصلح هذه المشكلة من الجذر.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE credits
    ADD COLUMN IF NOT EXISTS direction VARCHAR(10) NOT NULL DEFAULT 'debit';

-- ✅ قيد فحص (CHECK) يمنع أي قيمة غير 'debit' أو 'credit' من التسرّب لقاعدة
-- البيانات عبر أي مسار (حتى لو تم تجاوز التحقق على مستوى الواجهة/الـ API).
ALTER TABLE credits
    ADD CONSTRAINT chk_credits_direction
        CHECK (direction IN ('debit', 'credit'));

COMMENT ON COLUMN credits.direction IS
    'اتجاه القيد: debit = عليه (مستحق من العميل للمتجر) | credit = له (مستحق للعميل من المتجر)';

-- فهرس بسيط يُسرّع تجميع/تصفية الذمم حسب الاتجاه (مستخدَم في التقارير
-- المالية وحسابات رأس المال التي تفصل الذمم "عليه" عن أرصدة "له").
CREATE INDEX IF NOT EXISTS idx_credits_direction ON credits(direction);
